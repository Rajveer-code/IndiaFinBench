# ── Scoring ───────────────────────────────────────────────────────────────────

def normalise(text: str) -> str:
    if not text:
        return ""
    t = str(text).lower().strip()
    t = re.sub(r"[^\w\s%.]", " ", t)
    return re.sub(r"\s+", " ", t).strip()


def extract_yn(text: str) -> str:
    t = normalise(text)
    if t.startswith("yes"):
        return "yes"
    if t.startswith("no"):
        return "no"
    return "unclear"


def score_pair(ref: str, pred: str, task_type: str) -> int:
    """4-stage matching: exact → fuzzy token → numerical → Yes/No (CON)."""
    from rapidfuzz import fuzz

    if not pred:
        return 0

    if task_type == "contradiction_detection":
        return int(extract_yn(ref) == extract_yn(pred))

    rn, pn = normalise(ref), normalise(pred)

    # Stage 1: exact match (case-normalised, punctuation stripped)
    if rn == pn:
        return 1

    # Stage 2: numerical extraction match
    nums_r = set(re.findall(r"\d[\d,]*\.?\d*", rn))
    nums_p = set(re.findall(r"\d[\d,]*\.?\d*", pn))
    if nums_r and nums_p and nums_r == nums_p:
        return 1

    # Stage 3: fuzzy token match
    if fuzz.token_set_ratio(rn, pn) / 100.0 >= 0.72:
        return 1

    return 0


# ── Load original 60-item results from kappa_report.csv ──────────────────────

def load_original_60(path: str) -> dict:
    """Returns {task_type: [agree_int, ...]} from the original 60-item IAA."""
    results: dict[str, list] = {t: [] for t in TASK_ORDER}
    if not os.path.exists(path):
        print(f"  WARN: {path} not found — original 60 items not included.")
        return results
    with open(path, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            t = row.get("task_type", "")
            if t in results:
                results[t].append(int(row["agree"]))
    return results


# ── Score the returned expansion sheet ───────────────────────────────────────

def score_expansion(returned_path: str) -> dict:
    """Returns {task_type: [(agree_int, ref_yn, ann_yn), ...]} for n=60 new items."""
    # Load reference answers
    ref_map: dict[str, dict] = {}
    with open(REFERENCE_PATH, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            ref_map[row["item_id"]] = row

    results: dict[str, list] = {t: [] for t in TASK_ORDER}
    con_ref_labels: list[str] = []
    con_ann_labels: list[str] = []

    with open(returned_path, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            item_id = row.get("item_id", "").strip()
            ann_ans = row.get("YOUR_ANSWER", "").strip()

            if item_id not in ref_map:
                print(f"  WARN: item_id {item_id!r} not in reference — skipping")
                continue

            ref_row  = ref_map[item_id]
            task     = ref_row["task_type"]
            ref_ans  = ref_row["reference_answer"]

            agree = score_pair(ref_ans, ann_ans, task)
            results[task].append(agree)

            if task == "contradiction_detection":
                con_ref_labels.append(extract_yn(ref_ans))
                con_ann_labels.append(extract_yn(ann_ans))

    return results, con_ref_labels, con_ann_labels


# ── Print combined table ──────────────────────────────────────────────────────

def print_combined_table(orig: dict, exp_results: dict,
                         exp_con_ref: list, exp_con_ann: list):
    print()
    print(f"  {'━'*68}")
    print(f"  IndiaFinBench — Combined IAA Report (n=120)")
    print(f"  {'━'*68}")
    print(f"  {'Task Type':<32}  {'n_orig':>6}  {'n_new':>5}  {'n_total':>7}  {'Agree%':>7}  {'κ':>7}")
    print(f"  {'─'*32}  {'─'*6}  {'─'*5}  {'─'*7}  {'─'*7}  {'─'*7}")

    combined: dict[str, dict] = {}
    all_agrees: list[int] = []

    con_ref_all: list[str] = []
    con_ann_all: list[str] = []

    # Rebuild CON labels from original kappa_report for kappa calculation
    orig_con_ref: list[str] = []
    orig_con_ann: list[str] = []
    if os.path.exists(ORIGINAL_IAA):
        with open(ORIGINAL_IAA, encoding="utf-8") as f:
            for row in csv.DictReader(f):
                if row.get("task_type") == "contradiction_detection":
                    orig_con_ref.append(extract_yn(row.get("ref_answer", "")))
                    orig_con_ann.append(extract_yn(row.get("ann2_answer", "")))

    for t in TASK_ORDER:
        o = orig.get(t, [])
        e = exp_results.get(t, [])
        combined_agrees = o + e
        n_orig  = len(o)
        n_new   = len(e)
        n_total = len(combined_agrees)
        agree_pct = sum(combined_agrees) / n_total * 100 if n_total else 0.0
        all_agrees.extend(combined_agrees)

        kappa_str = "    N/A"
        kappa_val = None
        if t == "contradiction_detection":
            all_con_ref = orig_con_ref + exp_con_ref
            all_con_ann = orig_con_ann + exp_con_ann
            con_ref_all = all_con_ref
            con_ann_all = all_con_ann
            if len(set(all_con_ref)) > 1 and len(set(all_con_ann)) > 1:
                try:
                    kappa_val = cohen_kappa_score(all_con_ref, all_con_ann)
                    kappa_str = f"  {kappa_val:>5.3f}"
                except Exception:
                    kappa_str = "   ERR"

        combined[t] = {
            "n_orig":    n_orig,
            "n_new":     n_new,
            "n_total":   n_total,
            "agree_pct": agree_pct,
            "kappa":     kappa_val,
            "kappa_str": kappa_str,
        }
        print(f"  {t:<32}  {n_orig:>6}  {n_new:>5}  {n_total:>7}  {agree_pct:>6.1f}%  {kappa_str}")

    overall_agree = sum(all_agrees) / len(all_agrees) * 100 if all_agrees else 0.0
    n_total = len(all_agrees)
    print(f"  {'─'*32}  {'─'*6}  {'─'*5}  {'─'*7}  {'─'*7}  {'─'*7}")
    print(f"  {'OVERALL':<32}  {'':>6}  {'':>5}  {n_total:>7}  {overall_agree:>6.1f}%       --")
    print(f"  {'━'*68}")
    print()

    # Compute CON kappa
    con_kappa = combined["contradiction_detection"]["kappa"]

    print("  ── Paste into paper (Table 4 values) ──")
    print(f"  REG: n={combined['regulatory_interpretation']['n_total']}, agree={combined['regulatory_interpretation']['agree_pct']:.1f}%, κ=—")
    print(f"  NUM: n={combined['numerical_reasoning']['n_total']}, agree={combined['numerical_reasoning']['agree_pct']:.1f}%, κ=—")
    print(f"  CON: n={combined['contradiction_detection']['n_total']}, agree={combined['contradiction_detection']['agree_pct']:.1f}%, κ={con_kappa:.3f}" if con_kappa else f"  CON: n={combined['contradiction_detection']['n_total']}, agree={combined['contradiction_detection']['agree_pct']:.1f}%")
    print(f"  TMP: n={combined['temporal_reasoning']['n_total']}, agree={combined['temporal_reasoning']['agree_pct']:.1f}%, κ=—")
    print(f"  Overall: n={n_total}, agree={overall_agree:.1f}%")
    print()

    return combined, overall_agree, n_total


