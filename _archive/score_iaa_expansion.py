# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--returned_sheet", required=True,
                        help="Path to the filled annotator CSV")
    parser.add_argument("--patch_docx", action="store_true",
                        help="Also create IndiaFinBench_v5_IAA.docx")
    args = parser.parse_args()

    if not os.path.exists(args.returned_sheet):
        print(f"ERROR: returned sheet not found: {args.returned_sheet}")
        sys.exit(1)
    if not os.path.exists(REFERENCE_PATH):
        print(f"ERROR: reference file not found: {REFERENCE_PATH}")
        print("  Run generate_iaa_expansion.py first.")
        sys.exit(1)

    print(f"\n  Scoring expansion sheet: {args.returned_sheet}")

    # Score new 60 items
    exp_results, exp_con_ref, exp_con_ann = score_expansion(args.returned_sheet)

    # Load original 60-item data
    orig = load_original_60(ORIGINAL_IAA)

    # Print combined table and collect stats
    combined, overall_agree, n_total = print_combined_table(
        orig, exp_results, exp_con_ref, exp_con_ann
    )

    con_kappa = combined["contradiction_detection"]["kappa"]

    if args.patch_docx:
        if not os.path.exists(SRC_DOCX):
            print(f"  ERROR: source docx not found: {SRC_DOCX}")
        else:
            patch_docx(combined, overall_agree, n_total, con_kappa)


